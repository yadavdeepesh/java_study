package string_builder;

// Java program to demonstrate toString() Method

public class Geeks {
    public static void main(String[] args) {
        // create the string builder object 
        // with a string pass a parameter

        StringBuilder str = new StringBuilder("Geeks for Geeks");

        // print and display the string 
        // using the standard toString() method
        System.out.println("String are :: "+ str.toString());
    }
}
